export function icon(name, cls = '') {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('class', `icon ${cls}`.trim());
  svg.setAttribute('aria-hidden', 'true');
  svg.innerHTML = ICONS[name] || '';
  return svg;
}

/* Formatting ------------------------------------------------------------- */
const rtf = new Intl.RelativeTimeFormat(undefined, { numeric: 'auto', style: 'short' });
const UNITS = [
  ['year', 31536000],
  ['month', 2592000],
  ['week', 604800],
  ['day', 86400],
  ['hour', 3600],
  ['minute', 60],
];

export function timeAgo(date) {
  const seconds = Math.round((new Date(date).getTime() - Date.now()) / 1000);
  if (Math.abs(seconds) < 45) return 'just now';
  for (const [unit, size] of UNITS) {
    if (Math.abs(seconds) >= size || unit === 'minute') return rtf.format(Math.round(seconds / size), unit);
  }
  return '';
}

export function fullDate(date) {
  return new Date(date).toLocaleString(undefined, { dateStyle: 'medium', timeStyle: 'short' });
}

export function compact(n) {
  return new Intl.NumberFormat(undefined, { notation: 'compact', maximumFractionDigits: 1 }).format(n || 0);
}

/* Avatars ---------------------------------------------------------------- */
const AVATAR_GRADIENTS = [
  ['#7c5cff', '#ff5c8a'],
  ['#06b6d4', '#3b82f6'],
  ['#f59e0b', '#ef4444'],
  ['#10b981', '#06b6d4'],
  ['#8b5cf6', '#ec4899'],
  ['#f97316', '#eab308'],
];

function hash(str) {
  let x = 0;
  for (const ch of str) x = (x * 31 + ch.charCodeAt(0)) >>> 0;
  return x;
}

export function initials(name = '') {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  return ((parts[0]?.[0] || '?') + (parts.length > 1 ? parts[parts.length - 1][0] : '')).toUpperCase();
}

export function avatar(user, size = 'md', { link = true } = {}) {
  const [a, b] = AVATAR_GRADIENTS[hash(user?.username || '') % AVATAR_GRADIENTS.length];
  const props = {
    class: `avatar avatar-${size}`,
    style: { '--avatar-bg': `linear-gradient(135deg, ${a}, ${b})` },
    title: user?.name,
  };
  const content = user?.avatar
    ? h('img', { src: user.avatar, alt: '', loading: 'lazy', decoding: 'async' })
    : h('span', { 'aria-hidden': 'true' }, initials(user?.name));
  if (link && user?.username) {
    return h('a', { ...props, href: `#/u/${user.username}`, 'aria-label': `${user.name}'s profile` }, content);
  }
  return h('span', props, content);
}

/* Rich text: @mentions, #hashtags and links rendered as safe nodes. ------- */
const TOKEN_RE = /(https?:\/\/[^\s<]+[^\s<.,:;"')\]!?])|(@[a-z0-9_]{3,20})|(#[\p{L}\p{N}_]{2,50})/giu;

export function richText(text) {
  const frag = document.createDocumentFragment();
  let last = 0;
  for (const match of text.matchAll(TOKEN_RE)) {
    if (match.index > last) frag.append(text.slice(last, match.index));
    const [token, url, mention] = match;
    if (url) frag.append(h('a', { class: 'link', href: url, target: '_blank', rel: 'noopener noreferrer nofollow' }, url));
    else if (mention) frag.append(h('a', { class: 'mention', href: `#/u/${mention.slice(1).toLowerCase()}` }, mention));
    else frag.append(h('span', { class: 'hashtag' }, token));
    last = match.index + token.length;
  }
  if (last < text.length) frag.append(text.slice(last));
  return frag;
}

export function debounce(fn, ms = 250) {
  let t;
  return (...args) => {
    clearTimeout(t);
    t = setTimeout(() => fn(...args), ms);
  };
}
